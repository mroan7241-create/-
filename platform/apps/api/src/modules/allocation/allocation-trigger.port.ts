/**
 * ============================================================
 * AllocationTriggerPort — بذرة (seam) لا محرّك
 * ============================================================
 *
 * **NODE-3 لا ينقل `AutoAllocation.gs` إطلاقًا.** هذا الملف يعرّف الحدّ
 * الذي سيقف عنده NODE-5 لاحقًا، لا أكثر.
 *
 * لماذا موجود أصلًا: في النظام القديم، `reviewBeneficiaryNeeds_` تستدعي
 * `runAutoAllocation_(associationId, user)` مباشرة بعد نجاح اعتماد يحمل
 * احتياجًا معتمدًا واحدًا على الأقل، و`bulkReviewBeneficiaries` تؤجّل ذلك
 * الاستدعاء وتشغّله **مرة واحدة لكل جمعية فريدة** بعد انتهاء الدفعة
 * (Patch 3.2A.1). منطق **متى** يُستدعى المحرّك ملكٌ لمسار المراجعة، أما
 * **ماذا** يفعل المحرّك فملكٌ لِNODE-5. لذلك يُنقَل التوقيت الآن كاملًا
 * ومُختبَرًا، ويبقى الجسد فارغًا حتى NODE-5.
 *
 * عقد صارم يجب أن يبقى صحيحًا عند استبدال التنفيذ في NODE-5:
 *  1. **لا يُستدعى داخل معاملة المراجعة أبدًا** — دائمًا بعد `COMMIT`
 *     الناجح، تمامًا كنمط "audit بعد الالتزام" المعتمد منذ NODE-1.1.
 *  2. **لا يُسقط قرارًا نجح فعليًا** — أي استثناء منه يُلتقَط ويُسجَّل
 *     تحذيرًا فقط (نفس عزل `runAutoAllocation_` في Legacy: قرار المراجعة
 *     يبقى ناجحًا، ويُبلَّغ الفشل عبر `allocationWarnings` بلا تحويل أي
 *     عنصر ناجح إلى فاشل).
 *  3. **مرة واحدة لكل جمعية فريدة في الدفعة**، لا مرة لكل مستفيد.
 *
 * لا يوجد في NODE-3 أي مخزون أجهزة، ولا وحدات أجهزة، ولا عهدة/تسليم،
 * ولا أي منطق تخصيص فعلي — تلك نطاقات NODE-4/NODE-5 ولم تُبدأ.
 */
export interface AllocationTriggerPort {
  /**
   * إشارة "حدث اعتماد في هذه الجمعية قد يفتح فرصة تخصيص".
   * لا تُعيد أي نتيجة يعتمد عليها المستدعي — النجاح/الفشل لا يغيّران قرار
   * المراجعة المُلتزَم مسبقًا.
   */
  triggerForAssociation(associationId: string): Promise<void>;
}

/** رمز الحقن — واجهة TypeScript لا وجود لها زمن التشغيل، فيلزم token صريح. */
export const ALLOCATION_TRIGGER_PORT = Symbol('ALLOCATION_TRIGGER_PORT');
